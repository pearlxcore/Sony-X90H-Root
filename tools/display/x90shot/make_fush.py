"""make_fush.py - generate a fastup shader set (fu-*.frag) with zoom + tone (2026-11-16).

  python make_fush.py OUTDIR [--zoom ZX ZY] [--tone "R:lift,gain,gamma G:... B:..."]

Copies the four fastup shaders from evidence/latency-20261115/engine-ll/fastup and edits:
  fu-h.frag  horizontal source mapping magnified by ZX about the content centre
  fu-v.frag  source mapping (vertical filter, block clamp, sharpen) magnified by (ZX,ZY);
             the htex column lookup stays unmagnified (htex is already zoomed horizontally);
             final colour passed through  out = lift + gain * in^gamma  per channel
Run the engine with -Dx90.fastup=1 and FUSH=<device copy of OUTDIR>."""
import argparse
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.normpath(os.path.join(HERE, '..', '..', 'evidence', 'latency-20261115', 'engine-ll', 'fastup'))


def defines(zx, zy, tone):
    lift = 'vec3(%.5f,%.5f,%.5f)' % tuple(tone[c][0] for c in 'RGB')
    gain = 'vec3(%.5f,%.5f,%.5f)' % tuple(tone[c][1] for c in 'RGB')
    gam = 'vec3(%.5f,%.5f,%.5f)' % tuple(tone[c][2] for c in 'RGB')
    return ('// generated by tools/x90shot/make_fush.py zoom=(%.4f,%.4f)\n#define X90_ZX %.5f\n'
            '#define X90_ZOOM vec2(%.5f,%.5f)\n#define X90_LIFT %s\n#define X90_GAIN %s\n#define X90_GAMMA %s\n'
            % (zx, zy, zx, zx, zy, lift, gain, gam))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('out')
    ap.add_argument('--zoom', nargs=2, type=float, default=[1.0, 1.0])
    ap.add_argument('--tone', default='')
    a = ap.parse_args()
    tone = {c: (0.0, 1.0, 1.0) for c in 'RGB'}
    for part in a.tone.split():
        c, v = part.split(':')
        tone[c] = tuple(float(x) for x in v.split(','))
    os.makedirs(a.out, exist_ok=True)
    hdr = defines(a.zoom[0], a.zoom[1], tone)
    for name in ('fu-pre-block.frag', 'fu-pre-cross.frag', 'fu-h.frag', 'fu-v.frag'):
        t = open(os.path.join(SRC, name)).read()
        if name == 'fu-h.frag':
            old = 'float p=gl_FragCoord.x/outW*size.x;'
            assert t.count(old) == 1
            t = t.replace(old, 'float p=((gl_FragCoord.x/outW-0.5)/X90_ZX+0.5)*size.x;')
        if name == 'fu-v.frag':
            old = 'vec2 p=fc/outsize*size;'
            assert t.count(old) == 1
            t = t.replace(old, 'vec2 p=((fc/outsize-0.5)/X90_ZOOM+0.5)*size;')
            old = 'color=vec4(result,1.0);'
            assert t.count(old) == 1
            t = t.replace(old, 'result=clamp(X90_LIFT+X90_GAIN*pow(max(result,vec3(0.0)),X90_GAMMA),0.0,1.0);color=vec4(result,1.0);')
        if name in ('fu-h.frag', 'fu-v.frag'):
            t = re.sub(r'(#version 310 es\n)', lambda m: m.group(1) + hdr, t, count=1)
        open(os.path.join(a.out, name), 'w', newline='\n').write(t)
    print('wrote', a.out)


if __name__ == '__main__':
    main()
