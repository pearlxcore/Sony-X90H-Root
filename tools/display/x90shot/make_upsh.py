"""make_upsh.py - generate X90 engine upscale-shader variants (2026-11-16).

  python make_upsh.py OUT.frag --base catmull|easu|easufast [--zoom ZX ZY]
                      [--tone "R:lift,gain,gamma G:... B:..."]

Writes a drop-in replacement for catmullrom-clamped.frag (run the engine WITHOUT
-Dx90.fastup and pass it with UPSH=). Keeps the interface the engine expects:
uniforms src/outsize/sharpen and exactly one "gl_FragCoord.xy/outsize" (which the
engine rewrites to offset the 4:3 window).
  --zoom ZX ZY   magnify the picture about the content centre (Sony applies ~1.035 V)
  --tone ...     per-channel output curve  out = lift + gain * in^gamma  (clamped 0..1),
                 e.g. from x90shot_cmp.py "tone fit" lines (Sony = f(Engine)).
Base sources: native/field-engine-vt/catmullrom-clamped.frag and native/upscale-easu.frag."""
import argparse
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
NATIVE = os.path.normpath(os.path.join(HERE, '..', '..', 'native'))
BASES = {'catmull': os.path.join(NATIVE, 'field-engine-vt', 'catmullrom-clamped.frag'),
         'easu': os.path.join(NATIVE, 'upscale-easu.frag'),
         'easufast': os.path.join(NATIVE, 'upscale-easu-fast.frag')}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('out')
    ap.add_argument('--base', choices=BASES, default='easu')
    ap.add_argument('--zoom', nargs=2, type=float, default=[1.0, 1.0])
    ap.add_argument('--tone', default='')
    a = ap.parse_args()
    t = open(BASES[a.base]).read()
    assert t.count('gl_FragCoord.xy/outsize') == 1
    zx, zy = a.zoom
    tone = {c: (0.0, 1.0, 1.0) for c in 'RGB'}
    for part in a.tone.split():
        c, v = part.split(':')
        tone[c] = tuple(float(x) for x in v.split(','))
    lift = 'vec3(%.5f,%.5f,%.5f)' % tuple(tone[c][0] for c in 'RGB')
    gain = 'vec3(%.5f,%.5f,%.5f)' % tuple(tone[c][1] for c in 'RGB')
    gam = 'vec3(%.5f,%.5f,%.5f)' % tuple(tone[c][2] for c in 'RGB')
    # 1) zoom: remap the normalised content coordinate about the centre.
    if a.base == 'catmull':
        t = t.replace('vec2 p=gl_FragCoord.xy/outsize*size;',
                      'vec2 uvz=(gl_FragCoord.xy/outsize-0.5)/X90_ZOOM+0.5;vec2 p=uvz*size;')
    else:
        t = t.replace('vec2 uv=gl_FragCoord.xy/outsize;',
                      'vec2 uv=(gl_FragCoord.xy/outsize-0.5)/X90_ZOOM+0.5;')
    assert 'X90_ZOOM' in t
    # 2) tone: wrap the final colour write.
    assert t.count('color=vec4(result,1.0);') == 1
    t = t.replace('color=vec4(result,1.0);',
                  'result=clamp(X90_LIFT+X90_GAIN*pow(max(result,vec3(0.0)),X90_GAMMA),0.0,1.0);color=vec4(result,1.0);')
    header = ('// generated by tools/x90shot/make_upsh.py: base=%s zoom=(%.4f,%.4f) tone=%s\n'
              '#define X90_ZOOM vec2(%.5f,%.5f)\n#define X90_LIFT %s\n#define X90_GAIN %s\n#define X90_GAMMA %s\n'
              % (a.base, zx, zy, a.tone or 'identity', zx, zy, lift, gain, gam))
    t = re.sub(r'(#version 310 es\n)', r'\1' + header.replace('\\', '\\\\'), t, count=1)
    open(a.out, 'w', newline='\n').write(t)
    print('wrote', a.out)


if __name__ == '__main__':
    main()
